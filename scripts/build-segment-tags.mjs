/**
 * build-segment-tags.mjs
 *
 * Step 5 of the interview analysis system: validate + emit segment tags.
 *
 * Reads AI-proposed annotations from segment_tags.proposed.json (produced by
 * propose-segment-tags.mjs) and the codebook, validates every annotation for
 * integrity, and writes the canonical segment_tags.json.
 *
 * This script makes NO tagging judgements of its own — it is a pure validator.
 * All tag labels come from segment_tags.proposed.json; every annotation is
 * written review_status "pending" for analyst review before downstream use.
 *
 * (Tagging used to live in a hand-coded TAGS table here. That table is now
 * generated by propose-segment-tags.mjs via the Claude API; this script kept
 * its integrity role.)
 *
 * Integrity checks — any failure exits non-zero and writes nothing:
 *  - every proposal key is a real segment_id
 *  - an interview is either fully proposed or not at all (no partial coverage)
 *  - every theme / subtheme / emotion id exists in codebook.json
 *  - every subtheme's parent theme is also applied to the segment
 *  - sentiment is an integer in [-2, 2]; confidence is a number in [0, 1]
 *  - every topic id (if topic tagging has run) exists in topics.json
 *
 * Conversation topics are an optional, additive dimension produced by
 * propose-topics.mjs. If that step has not run, annotations get topics: [].
 *
 * Run:
 *   node scripts/propose-segment-tags.mjs   # first, to generate proposals
 *   node scripts/build-segment-tags.mjs
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

const SEGMENTS_FILE = 'src/lib/content/wctglpdemo-data/segments.json';
const CODEBOOK_FILE = 'src/lib/content/wctglpdemo-data/codebook.json';
const PROPOSED_FILE = 'src/lib/content/wctglpdemo-data/segment_tags.proposed.json';
const TOPICS_FILE = 'src/lib/content/wctglpdemo-data/topics.json';
const TOPIC_ASSIGNMENTS_FILE = 'src/lib/content/wctglpdemo-data/topic_tags.proposed.json';
const OUTPUT_FILE = 'src/lib/content/wctglpdemo-data/segment_tags.json';

// --- Load inputs ---
if (!existsSync(resolve(ROOT, PROPOSED_FILE))) {
	console.error(`x ${PROPOSED_FILE} not found.`);
	console.error('  Generate proposals first: node scripts/propose-segment-tags.mjs');
	process.exit(1);
}

const segmentsData = JSON.parse(readFileSync(resolve(ROOT, SEGMENTS_FILE), 'utf8'));
const codebook = JSON.parse(readFileSync(resolve(ROOT, CODEBOOK_FILE), 'utf8'));
const proposedData = JSON.parse(readFileSync(resolve(ROOT, PROPOSED_FILE), 'utf8'));
const PROPOSALS = proposedData.proposals ?? {};

// Topics are an optional, additive dimension (an open, emergent vocabulary).
// If propose-topics.mjs has not run, every annotation simply gets topics: [].
let topicAssignments = {};
let validTopics = new Set();
let topicsStatus = 'not_run';
if (existsSync(resolve(ROOT, TOPIC_ASSIGNMENTS_FILE))) {
	if (!existsSync(resolve(ROOT, TOPICS_FILE))) {
		console.error(`x ${TOPIC_ASSIGNMENTS_FILE} exists but ${TOPICS_FILE} is missing.`);
		process.exit(1);
	}
	topicAssignments =
		JSON.parse(readFileSync(resolve(ROOT, TOPIC_ASSIGNMENTS_FILE), 'utf8')).assignments ?? {};
	validTopics = new Set(
		JSON.parse(readFileSync(resolve(ROOT, TOPICS_FILE), 'utf8')).topics.map((t) => t.id)
	);
	topicsStatus = 'present';
}

const validThemes = new Set(codebook.themes.map((t) => t.id));
const validEmotions = new Set(codebook.emotion_tags.map((t) => t.id));
// subtheme id -> parent theme id
const subthemeParent = new Map();
for (const theme of codebook.themes) {
	for (const sub of theme.subthemes ?? []) subthemeParent.set(sub.id, theme.id);
}

const segmentsById = new Map(segmentsData.segments.map((s) => [s.segment_id, s]));
const segmentsByInterview = new Map();
for (const s of segmentsData.segments) {
	if (!segmentsByInterview.has(s.interview_id)) segmentsByInterview.set(s.interview_id, []);
	segmentsByInterview.get(s.interview_id).push(s);
}

const errors = [];
const annotations = [];

// --- Coverage: every proposal maps to a real segment ---
for (const id of Object.keys(PROPOSALS)) {
	if (!segmentsById.has(id)) errors.push(`Proposal for unknown segment_id "${id}".`);
}

// --- Coverage: each interview is fully proposed or not at all ---
const taggedInterviews = [];
const pendingInterviews = [];
for (const [interviewId, segs] of [...segmentsByInterview].sort((a, b) => a[0].localeCompare(b[0]))) {
	const have = segs.filter((s) => s.segment_id in PROPOSALS).length;
	if (have === 0) {
		pendingInterviews.push(interviewId);
		continue;
	}
	if (have !== segs.length) {
		errors.push(
			`${interviewId}: partial coverage — ${have}/${segs.length} segments have proposals. ` +
				`Re-run: node scripts/propose-segment-tags.mjs ${interviewId} --force`
		);
	}
	taggedInterviews.push(interviewId);
}

// --- Per-annotation integrity ---
for (const [segmentId, value] of Object.entries(PROPOSALS)) {
	const seg = segmentsById.get(segmentId);
	if (!seg) continue; // already reported above

	const themes = value.themes ?? [];
	const subthemes = value.subthemes ?? [];
	const emotions = value.emotions ?? [];
	const { sentiment, confidence } = value;
	const note = value.note ?? '';

	for (const t of themes) if (!validThemes.has(t)) errors.push(`${segmentId}: unknown theme "${t}".`);
	for (const e of emotions) if (!validEmotions.has(e)) errors.push(`${segmentId}: unknown emotion "${e}".`);
	for (const st of subthemes) {
		const parent = subthemeParent.get(st);
		if (!parent) {
			errors.push(`${segmentId}: unknown subtheme "${st}".`);
		} else if (!themes.includes(parent)) {
			errors.push(
				`${segmentId}: subtheme "${st}" requires parent theme "${parent}" to also be applied.`
			);
		}
	}
	if (!Number.isInteger(sentiment) || sentiment < -2 || sentiment > 2) {
		errors.push(`${segmentId}: sentiment must be an integer in [-2, 2], got ${sentiment}.`);
	}
	if (typeof confidence !== 'number' || confidence < 0 || confidence > 1) {
		errors.push(`${segmentId}: confidence must be between 0 and 1, got ${confidence}.`);
	}

	const topics = topicAssignments[segmentId] ?? [];
	for (const tp of topics) {
		if (!validTopics.has(tp)) errors.push(`${segmentId}: unknown topic "${tp}" (not in topics.json).`);
	}

	annotations.push({
		segment_id: segmentId,
		interview_id: seg.interview_id,
		question_id: seg.question_id,
		topics,
		themes,
		subthemes,
		emotions,
		sentiment,
		confidence,
		source: 'ai_proposed',
		review_status: 'pending',
		reviewer_notes: note
	});
}

if (errors.length > 0) {
	console.error(`x Validation failed with ${errors.length} error(s). Output not written.`);
	for (const e of errors) console.error(`  - ${e}`);
	process.exit(1);
}

annotations.sort((a, b) => a.segment_id.localeCompare(b.segment_id));

const output = {
	meta: {
		schema_version: '1.2',
		study_id: segmentsData.meta.study_id,
		generated_at: new Date().toISOString(),
		generator: 'scripts/build-segment-tags.mjs',
		sources: [SEGMENTS_FILE, CODEBOOK_FILE, PROPOSED_FILE],
		codebook_schema_version: codebook.meta.schema_version,
		labels_status: 'ai_proposed',
		labels_model: proposedData.meta?.model ?? 'unknown',
		proposals_generated_at: proposedData.meta?.generated_at ?? null,
		topics_status: topicsStatus,
		tagged_interviews: taggedInterviews,
		pending_interviews: pendingInterviews,
		notes: [
			'Theme/subtheme/emotion/sentiment tags are AI-proposed; every annotation is review_status "pending".',
			'Tags are proposed by scripts/propose-segment-tags.mjs and re-validated here against codebook.json.',
			'A subtheme is only valid when its parent theme is also applied to the segment.',
			'`topics` is an open, emergent vocabulary from scripts/propose-topics.mjs (topics.json); [] when topic tagging has not run.',
			'Annotations are keyed by segment_id and join back to segments.json (which carries char offsets).',
			'pending_interviews lists interviews not yet tagged, so their segments are not mistaken for untagged-by-analysis.'
		]
	},
	annotations
};

writeFileSync(resolve(ROOT, OUTPUT_FILE), JSON.stringify(output, null, 2) + '\n', 'utf8');

console.log(`Wrote ${OUTPUT_FILE} (${annotations.length} annotations)`);
console.log(`  tagged: ${taggedInterviews.join(', ') || '(none)'}`);
console.log(`  pending: ${pendingInterviews.join(', ') || '(none)'}`);

const themeFreq = {};
const subFreq = {};
for (const a of annotations) {
	for (const t of a.themes) themeFreq[t] = (themeFreq[t] ?? 0) + 1;
	for (const s of a.subthemes) subFreq[s] = (subFreq[s] ?? 0) + 1;
}
const topThemes = Object.entries(themeFreq)
	.sort((a, b) => b[1] - a[1])
	.slice(0, 8);
console.log(`  top themes: ${topThemes.map(([t, n]) => `${t}(${n})`).join(', ')}`);
const subCount = Object.values(subFreq).reduce((n, v) => n + v, 0);
console.log(`  ${subCount} subtheme tags across ${Object.keys(subFreq).length} distinct subthemes`);

if (topicsStatus === 'present') {
	const topicFreq = {};
	for (const a of annotations) for (const t of a.topics) topicFreq[t] = (topicFreq[t] ?? 0) + 1;
	const topTopics = Object.entries(topicFreq)
		.sort((a, b) => b[1] - a[1])
		.slice(0, 6);
	console.log(
		`  topics: ${Object.keys(topicFreq).length} distinct; top: ${topTopics.map(([t, n]) => `${t}(${n})`).join(', ')}`
	);
} else {
	console.log(`  topics: not run (node scripts/propose-topics.mjs)`);
}

const lowConf = annotations.filter((a) => a.confidence < 0.7);
console.log(`  ${lowConf.length} annotation(s) below 0.7 confidence flagged for priority review`);
